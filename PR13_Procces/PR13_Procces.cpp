#include <iostream>
#include <fstream>
#include <cmath>
#include <string>

using namespace std;





int main(int argc, char* argv[])
{
    if (argc != 4) {
        cout << "Ошибка: нужно передать 3 аргумента(начало, конец, имя)" << endl;
        return 1;
    }
    
    int start = stoi(argv[1]);
    int end = stoi(argv[2]);
    string filename = argv[3];

    int count = 0;

    for (int i = start; i <= end; i++)
    {
        bool prost = true;
        if (i <= 1) prost = false;
        for (int j = 2; j <= sqrt(i); j++) {
            if (i % j == 0) {
                prost = false;
                break;
            }
        }
        if (prost) count++;
    }

    ofstream out(filename);
    out << count << endl;
    out.close();

    return 0;
}

